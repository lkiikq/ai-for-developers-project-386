// In-memory хранилище данных (см. README: только память процесса,
// без БД и файловых сохранений). При перезапуске сервера данные сбрасываются.
// Вся работа с данными идёт через этот модуль, чтобы при необходимости
// заменить его на БД, не меняя остальной код.
const store = {
  eventTypes: [],
  bookings: [],
};

// Сброс состояния — используется в тестах перед каждым тестом.
export const resetStore = () => {
  store.eventTypes = [];
  store.bookings = [];
};

export default store;
