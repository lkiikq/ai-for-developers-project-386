// In-memory хранилище данных (см. README: только память процесса,
// без БД и файловых сохранений). При перезапуске сервера данные сбрасываются,
// но типы встреч по умолчанию создаются заново.
// Вся работа с данными идёт через этот модуль, чтобы при необходимости
// заменить его на БД, не меняя остальной код.

// Типы встреч, которые есть «из коробки»: 30 и 60 минут (см. README,
// «Хранение данных»). `id` фиксированные, чтобы ссылки на них были стабильными.
const defaultEventTypes = () => [
  {
    id: 'default-30',
    title: 'Созвон на 30 минут',
    description: 'Короткий созвон, чтобы обсудить вопросы по делу.',
    durationMinutes: 30,
  },
  {
    id: 'default-60',
    title: 'Созвон на час',
    description: 'Разговор без спешки: разбор деталей и планов.',
    durationMinutes: 60,
  },
];

const store = {
  eventTypes: defaultEventTypes(),
  bookings: [],
};

// Сброс состояния — используется в тестах перед каждым тестом:
// возвращает хранилище в исходное (стартовое) состояние с типами по умолчанию.
export const resetStore = () => {
  store.eventTypes = defaultEventTypes();
  store.bookings = [];
};

export default store;
